// سعر واضح صديق للـOCR بأرقام لاتينية وعملة "ر.س" — صيغ المجلات الغريبة
// (٩٫٩٥ و"2 بـ 15") مغطّاة بفحوص وحدة على المُحلّل لضمان الحتمية.
function priceMarkup(i) {
  const base = 4 + ((i * 7) % 40) + (i % 2 ? 0.95 : 0.5);
  const p = Math.round(base * 100) / 100;
  const prefix = i % 3 === 0 ? 'السعر ' : '';
  return `<span class="price">${prefix}${p.toFixed(2)} ر.س</span>`;
}

function itemCard(it, i) {
  const [name, brand, size] = it;
  const title = [name, brand, size].filter(Boolean).join(' ');
  // صف بعرض كامل: الاسم يميناً والسعر يساراً على نفس السطر — أوضح للـOCR
  return `<div class="card"><span class="name">${title}</span><span class="row">${priceMarkup(i)}</span></div>`;
}

